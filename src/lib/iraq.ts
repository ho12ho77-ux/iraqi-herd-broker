export function districtsOf(gov: string): District[] {
  return GOVERNORATES.find((g) => g.name === gov)?.districts ?? [];
}

export function areasOf(gov: string, district: string): string[] {
  return districtsOf(gov).find((x) => x.name === district)?.areas ?? [];
}
